/*
  Прокси картинок для превью.

  Зачем. Опубликованное превью живёт во фрейме со строгой политикой
  ресурсов. Картинка поставщика по прямому адресу в нём не появляется:
  src проставлен, файл по этому адресу открывается в отдельной вкладке и
  отдаёт 200, а в самом превью naturalWidth остаётся нулём. Значит дело
  не в файле и не в схеме, а в том, откуда фрейму разрешено грузить
  картинки.

  Прокси переписывает адрес на сторонний сервис, который заодно уменьшает
  картинку и отдаёт WebP. Это решение ТОЛЬКО для превью: боевой сайт
  ходит к поставщику напрямую и ни от какого третьего сервиса не зависит.
  Поэтому переписывание живёт здесь, на этапе сборки превью, а не в
  нормализации: в data/catalog остаются настоящие адреса поставщика.

  Если политика фрейма запрещает и этот хост, картинка всё равно не
  появится — тогда работает второй путь, упаковка уменьшенных копий в
  сам артефакт (tools/pack-thumbs.mjs). Оба пути не мешают друг другу.
*/

/* Сервис выбран за то, что у него нет обязательного ключа, он держит
   произвольный источник и умеет и ресайз, и WebP одним запросом. */
export const PROXY_ORIGIN = 'https://wsrv.nl/';

export const PROXY_WIDTHS = [320, 640];

/*
  Адрес источника передаётся без схемы: сервис подставляет её сам, а
  лишний «https://» в параметре у части CDN ломает подпись запроса.
  Кодируем целиком — в адресах поставщика встречаются и скобки, и
  кириллица.
*/
export function proxyUrl(url, { width = 320, quality = 78, output = 'webp' } = {}) {
  const s = String(url ?? '');
  const m = /^https?:\/\/(.+)$/i.exec(s);
  if (!m) return s;
  const params = new URLSearchParams({
    url: m[1],
    w: String(width),
    output,
    q: String(quality),
    /* Без увеличения: картинка меньше запрошенной ширины остаётся собой,
       растянутая выглядит хуже честной маленькой. */
    we: '',
  });
  return `${PROXY_ORIGIN}?${params.toString()}`;
}

export function proxySrcset(url, widths = PROXY_WIDTHS, opts = {}) {
  return widths.map((w) => `${proxyUrl(url, { ...opts, width: w })} ${w}w`).join(', ');
}

/* Адреса, которые вообще имеет смысл проксировать: чужие http(s)-хосты.
   Собственные файлы витрины лежат рядом со страницей и проксировать их
   незачем — это только добавило бы зависимость от третьего сервиса. */
export function shouldProxy(url) {
  return /^https?:\/\//i.test(String(url ?? ''));
}
