/* Уникальность считается по «голому» тексту: снимаем название, артикул,
   код товара, марку и общие служебные обороты — то есть всё, чем шаблон
   маскируется под индивидуальный текст. */
const STOPWORDS = /(?:артикул\w*|код товара|hi-?black|netproduct|поставщик\w*|каталог\w*|напишите нам|уточняйте|перед заказом)/gi;
function bare(text, f) {
  let t = ' ' + text.toLowerCase() + ' ';
  if (f.name) t = t.split(f.name.toLowerCase()).join(' ');
  if (f.code) t = t.split(f.code.toLowerCase()).join(' ');
  if (f.no) t = t.split(String(f.no).toLowerCase()).join(' ');
  if (f.brandTitle) t = t.split(f.brandTitle.toLowerCase()).join(' ');
  return t.replace(STOPWORDS, ' ').replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}
function shingles(t) {
  const w = t.split(' ').filter(Boolean);
  const s = new Set();
  for (let i = 0; i + 5 <= w.length; i++) s.add(w.slice(i, i + 5).join(' '));
  return s;
}
const jac = (a, b) => {
  let inter = 0;
  const [small, big] = a.size < b.size ? [a, b] : [b, a];
  for (const x of small) if (big.has(x)) inter++;
  return inter / (a.size + b.size - inter || 1);
};

const facts = {};
for (const row of idx.rows) facts[row[F.id]] = factsOf(row);

const shingleOf = {};
for (const [id, it] of Object.entries(items)) {
  shingleOf[id] = shingles(bare(textOf(it.sections.map((s) => [s.h, s.p])), facts[id]));
}
/* Сравниваем внутри групп «тип + марка»: полные дубли возможны только
   там, а полный перебор 3 636 позиций — это 6,6 млн пар. */
const buckets = {};
for (const [id, it] of Object.entries(items)) {
  const f = facts[id];
  const key = it.group + '|' + f.brand;
  (buckets[key] ||= []).push(id);
}
/*
  Порогов несколько намеренно.

  Один порог легко подобрать так, чтобы отчёт вышел красивым. Поэтому
  считаем сразу по нескольким: полное совпадение, почти полное и просто
  высокое сходство. Так видно не «сколько дублей», а насколько тексты
  расходятся на самом деле — и есть ли среди них пары, различающиеся
  только названием.
*/
const near = [], levels = { '1.00': 0, '0.90': 0, '0.80': 0, '0.70': 0 };
let pairs = 0, maxSim = 0, sumSim = 0;
for (const list of Object.values(buckets)) {
  for (let i = 0; i < list.length; i++) {
    for (let j = i + 1; j < list.length; j++) {
      const s = jac(shingleOf[list[i]], shingleOf[list[j]]);
      pairs += 1; sumSim += s;
      if (s > maxSim) maxSim = s;
      if (s >= 0.999) levels['1.00'] += 1;
      if (s >= 0.9) levels['0.90'] += 1;
      if (s >= 0.8) levels['0.80'] += 1;
      if (s >= 0.7) levels['0.70'] += 1;
      if (s >= 0.8) near.push({ a: list[i], b: list[j], sim: +s.toFixed(3) });
    }
  }
}
near.sort((x, y) => y.sim - x.sim);
