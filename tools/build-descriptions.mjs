function build(f) {
  const r = rnd(seed(f.id) || 1);
  const plan = (PLAN[f.group] || planOther)(f, r);
  const sections = plan
    .map(([h, paras]) => [h, (paras || []).map((x) => String(x || '').trim()).filter(Boolean)])
    .filter(([, paras]) => paras.length);
  return sections;
}

