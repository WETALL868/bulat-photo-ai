/*
  Цвета расходников.

  Поставщик присылает код («Bk», «C», «M», «Y», «4-COL»), а покупатель
  выбирает цвет глазами. Поэтому код переводится в русское название — но
  переводится, а не придумывается: таблица покрывает ровно те значения,
  которые встречаются в выгрузке, а всё незнакомое остаётся кодом как
  есть. Незнакомый код лучше показать как есть, чем назвать его наугад.

  Кириллическая «С» в поле цвета — не опечатка выгрузки, а реальность:
  семь позиций пришли с русской буквой вместо латинской. Сравнение идёт
  по нормализованному ключу, поэтому обе попадают в «Голубой».
*/

/* Ключ сравнения: нижний регистр, без ё и без знаков. */
export function colorKey(value) {
  return String(value ?? '')
    .trim().toLowerCase().replace(/ё/g, 'е')
    .replace(/[^0-9a-zа-я]/g, '');
}

const LABELS = new Map(Object.entries({
  bk: 'Чёрный', k: 'Чёрный', black: 'Чёрный', bl: 'Чёрный', b: 'Чёрный',
  с: 'Голубой', c: 'Голубой', cyan: 'Голубой',
  m: 'Пурпурный', magenta: 'Пурпурный',
  y: 'Жёлтый', yellow: 'Жёлтый',
  lc: 'Светло-голубой', lm: 'Светло-пурпурный',
  pbk: 'Фото-чёрный', pb: 'Фото-чёрный', pc: 'Фото-голубой', pm: 'Фото-пурпурный',
  mbk: 'Матовый чёрный',
  gy: 'Серый', gray: 'Серый', grey: 'Серый',
  r: 'Красный', red: 'Красный',
  co: 'Бесцветный', white: 'Белый',
  color: 'Цветной', colour: 'Цветной', cl: 'Цветной', ml: 'Многоцветный',
  cmyk: 'Четыре цвета', '3col': 'Три цвета', '4col': 'Четыре цвета',
  '5col': 'Пять цветов', '6col': 'Шесть цветов',
  /* Русские названия тоже ключи. В каталоге прототипа цвет изначально
     записан словом, и без этих строк он оставался бы «незнакомым»:
     порядок показа сбивался в тот, в каком товары легли в выгрузку. */
  черный: 'Чёрный', матовыйчерный: 'Матовый чёрный', фочерный: 'Фото-чёрный',
  фоточерный: 'Фото-чёрный', голубой: 'Голубой', светлоголубой: 'Светло-голубой',
  фотоголубой: 'Фото-голубой', пурпурный: 'Пурпурный', светлопурпурный: 'Светло-пурпурный',
  фотопурпурный: 'Фото-пурпурный', желтый: 'Жёлтый', красный: 'Красный', серый: 'Серый',
  синий: 'Чёрный', белый: 'Белый', бесцветный: 'Бесцветный', цветной: 'Цветной',
  многоцветный: 'Многоцветный',
}));

/* Русское название цвета или null, если код незнаком. */
export function colorLabel(value) {
  return LABELS.get(colorKey(value)) ?? null;
}

/*
  Подпись цвета для карточки: «Голубой (C)». Код остаётся на виду —
  по нему покупатель сверяется с надписью на картридже, и терять его
  ради красивого слова нельзя.
*/
export function colorTitle(value) {
  const code = String(value ?? '').trim();
  if (!code) return '';
  const label = colorLabel(code);
  if (!label) return code;
  return label.toLowerCase() === code.toLowerCase() ? label : `${label} (${code})`;
}

/*
  То же самое строчными буквами — для середины предложения. Строчным
  становится только название: код на картридже напечатан как напечатан,
  и «bk» вместо «Bk» покупателю уже не найти на коробке.
*/
export function colorPhrase(value) {
  const code = String(value ?? '').trim();
  if (!code) return '';
  const label = colorLabel(code);
  if (!label) return code;
  return label.toLowerCase() === code.toLowerCase() ? label.toLowerCase() : `${label.toLowerCase()} (${code})`;
}

/*
  Цвет для середины фразы: «чёрный тонер-картридж».

  Отличается от подписи в характеристиках двумя вещами. Кода в скобках
  нет — «Чёрный (Bk) тонер-картридж» читается как строка из накладной. И
  наборы переведены в прилагательное: «Три цвета картридж» не
  по-русски, а «трёхцветный картридж» — по-русски.

  Незнакомый код возвращает null: в характеристиках он останется как
  есть, а в текст непонятный набор букв не пойдёт.
*/
const ADJECTIVE = new Map(Object.entries({
  'Три цвета': 'трёхцветный',
  'Четыре цвета': 'четырёхцветный',
  'Пять цветов': 'пятицветный',
  'Шесть цветов': 'шестицветный',
}));

export function colorWord(value) {
  const label = colorLabel(value);
  if (!label) return null;
  return ADJECTIVE.get(label) ?? label.toLowerCase();
}

/* Порядок показа: как на панели принтера, а не по алфавиту. */
const ORDER = ['Чёрный', 'Матовый чёрный', 'Фото-чёрный', 'Серый', 'Голубой',
  'Светло-голубой', 'Фото-голубой', 'Пурпурный', 'Светло-пурпурный', 'Фото-пурпурный',
  'Жёлтый', 'Красный', 'Белый', 'Бесцветный', 'Цветной', 'Многоцветный',
  'Три цвета', 'Четыре цвета', 'Пять цветов', 'Шесть цветов'];

export function colorRank(value) {
  const i = ORDER.indexOf(colorLabel(value) ?? '');
  return i < 0 ? ORDER.length : i;
}
