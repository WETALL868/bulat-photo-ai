/*
  Серии по цветам.

  Один и тот же картридж выпускается в нескольких цветах, и для покупателя
  это одна покупка: он пришёл за голубым к своему Kyocera, а рядом должны
  быть чёрный, пурпурный и жёлтый той же серии — каждый со своей ценой,
  своим остатком, своим фото и своим адресом.

  Раньше в ключ серии входил ресурс, и на этом всё разваливалось. У
  HB-TK-8115 чёрный рассчитан на 12 000 страниц, а цветные на 6 000 —
  это нормально для любого цветного аппарата и не делает их разными
  сериями. Но ключ с ресурсом разводил их по четырём разным семействам, и
  выбора цвета на карточке не было вовсе.

  Теперь серия опознаётся по тому, что у цветов одной серии действительно
  совпадает:
    • марка поставщика (Hi-Black, NetProduct, …) — чужие марки не
      смешиваются;
    • раздел витрины и раздел поставщика — чипы не попадут к
      тонер-картриджам;
    • тип расходника;
    • марка техники, к которой товар подходит (Vendor у VTT);
    • название без артикула, без цвета и без ресурса.

  Ресурса в ключе нет намеренно, а цвет и артикул из названия вырезаются —
  иначе «…, Bk,12K» и «…, C, 6K» снова окажутся разными сериями.

  Что НЕ склеивается. Товар без цвета в серию не идёт вовсе. Серия из
  тринадцати и более позиций отбрасывается целиком: столько цветов не
  бывает даже у широкоформатных чернил, а значит ключ слишком общий и
  набор получился бы выдуманным. Слишком короткий остаток названия тоже
  отбрасывается: от такого ключа до склейки всего подряд один шаг.

  Повторяющийся цвет внутри серии — не ошибка. У Canon PFI-102 два
  чёрных (обычный и матовый), у чипов один и тот же цвет бывает в двух
  ресурсах. Такие позиции остаются обе, а в переключателе к названию
  цвета добавляется ресурс или объём — по нему их и различают.

  Модуль отдельный, а не строчки внутри сборщика: правила склейки это то
  место, где ошибка не видна глазом (комплект из восьми «цветов»
  выглядит правдоподобно), и проверяться они должны тестами.
*/
import { colorTitle } from './colors.mjs';

/* Токены цвета в названии: и слова, и коды с картриджа. Список закрытый —
   угадывать цвет по «похожести» нельзя. */
const COLOR_NAME_TOKENS = ['bk', 'k', 'black', 'bl', 'c', 'с', 'cyan', 'm', 'magenta', 'y', 'yellow',
  'lc', 'lm', 'pbk', 'pb', 'mbk', 'pc', 'pm', 'gy', 'gray', 'grey', 'r', 'red', 'co', 'white',
  'color', 'colour', 'cl', 'ml', 'cmyk',
  'ч[её]рн\\p{L}*', 'голуб\\p{L}*', 'пурпурн\\p{L}*', 'ж[её]лт\\p{L}*', 'син\\p{L}*',
  'красн\\p{L}*', 'сер\\p{L}*', 'цветн\\p{L}*', 'бесцветн\\p{L}*', 'бел\\p{L}*', 'матов\\p{L}*'];
/* Границы заданы явно: `\b` в JavaScript не работает с кириллицей — у
   русского слова границы по нему нет вовсе, и проверка молча пустая. */
const COLOR_TOKEN_RE = new RegExp(`(^|[^0-9\\p{L}])(${COLOR_NAME_TOKENS.join('|')})(?![0-9\\p{L}])`, 'giu');
const MULTICOLOR_RE = /(^|[^0-9\p{L}])\d\s*-?\s*col(?![0-9\p{L}])/giu;
const RESOURCE_RE = /(^|[^0-9\p{L}])\d+(?:[.,]\d+)?\s*[kк](?![0-9\p{L}])/giu;
const PAGES_RE = /\d[\d\s]*стр\.?/giu;

/*
  Название без артикула, цвета и ресурса — то, что остаётся общего у
  цветов одной серии. «Тип B» у универсальных чернил защищён от вырезания:
  без этого «Тип B» и «Тип C» слились бы в одну серию, хотя это разные
  чернила для разных аппаратов.
*/
const codeShape = (s) => String(s || '').toUpperCase().replace(/[^0-9A-ZА-Я]/g, '');
export function seriesKey(p) {
  let t = String(p.name || '');
  /*
    В скобках у VTT стоит не только артикул. «(Азия)» у HB-TK-8110 —
    это другая серия с другой ценой, и вычёркивать её нельзя: без этой
    оговорки HB-TK-8110 и HB-TK-8115 для одного и того же Kyocera
    сходятся в один ключ и склеиваются в комплект из восьми «цветов».
    Поэтому скобка убирается только тогда, когда внутри неё артикул.
  */
  const code = codeShape(p.code);
  t = t.replace(/\(([^)]*)\)/g, (m, inner) => {
    const shape = codeShape(inner);
    if (!code || !shape) return m;
    return shape === code || code.includes(shape) || shape.includes(code) ? ' ' : m;
  });
  if (p.code) t = t.split(p.code).join(' ');
  t = t.replace(PAGES_RE, ' ').replace(RESOURCE_RE, ' ').replace(MULTICOLOR_RE, ' ');
  t = t.replace(/(^|[^0-9\p{L}])(тип)\s+([0-9\p{L}]{1,3})(?![0-9\p{L}])/giu, (m, a, b, c) => `${a}${b}_${c}`);
  /* Два прохода: соседние токены «, C, M,» делят один разделитель, и за
     один проход второй из них не совпадает. */
  t = t.replace(COLOR_TOKEN_RE, '$1 ').replace(COLOR_TOKEN_RE, '$1 ');
  return t.toLowerCase().replace(/ё/g, 'е').replace(/[^0-9a-zа-я_]+/g, '');
}

export const famKey = (p) => [
  p.supplierBrand || p.brand, p.cat, p.vttCategoryId ?? '', p.type,
  p.compatibleBrand ?? '', seriesKey(p),
].join('|');

/* Столько цветов не бывает ни у одной серии: больше — значит ключ
   слишком общий, и набор был бы выдуман. */
export const FAM_MAX = 12;
export const FAM_MIN_SERIES = 8;


/* Подпись цвета в переключателе. Если в серии два «чёрных» — обычный и
   матовый, или один чип в двух ресурсах, — к названию добавляется то, чем
   они на самом деле различаются. Оба факта из выгрузки. */
export function variantLabel(p, ambiguous) {
  const base = colorTitle(p.color) || p.color || 'Цвет';
  if (!ambiguous) return base;
  if (p.res) return `${base} · ${Number(p.res).toLocaleString('ru-RU')} стр.`;
  if (p.volumeMl) return `${base} · ${Number(p.volumeMl).toLocaleString('ru-RU')} мл`;
  return `${base} · ${p.code}`;
}
